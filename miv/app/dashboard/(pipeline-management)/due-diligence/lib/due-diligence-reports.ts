export function getDefaultReportSections(reportType: string): ReportSections {
  const defaultSections: ReportSections = {}
  REPORT_SECTION_OPTIONS[reportType as ReportType]?.forEach((section) => {
    defaultSections[section.id] = section.default
  })
  return defaultSections
}

