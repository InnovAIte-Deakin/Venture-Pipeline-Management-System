export function downloadReport(content: string, filename: string, reportFormat: string): void {
  const blob = new Blob([content], { type: reportFormat === "pdf" ? "application/pdf" : "text/plain" })
  const url = window.URL.createObjectURL(blob)
  const a = document.createElement("a")
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  window.URL.revokeObjectURL(url)
}

